CREATE TABLE `run_partitions` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `backfill_run_id` bigint NOT NULL,
  `partition_name` varbinary(300) NOT NULL,
  `created_at` timestamp(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` timestamp(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  `version` bigint NOT NULL DEFAULT '0',
  `run_state` enum('PAUSED','RUNNING','COMPLETE','CANCELLED') NOT NULL,
  `lease_token` varbinary(300) DEFAULT NULL,
  `lease_expires_at` timestamp(3) NOT NULL,
  `pkey_cursor` varbinary(8192) DEFAULT NULL,
  `pkey_range_start` varbinary(8192) DEFAULT NULL,
  `pkey_range_end` varbinary(8192) DEFAULT NULL,
  `estimated_record_count` bigint DEFAULT NULL,
  `precomputing_pkey_cursor` varbinary(8192) DEFAULT NULL,
  `computed_scanned_record_count` bigint NOT NULL DEFAULT '0',
  `computed_matching_record_count` bigint NOT NULL DEFAULT '0',
  `precomputing_done` tinyint(1) NOT NULL DEFAULT '0',
  `backfilled_scanned_record_count` bigint NOT NULL DEFAULT '0',
  `backfilled_matching_record_count` bigint NOT NULL DEFAULT '0',
  `scanned_records_per_minute` bigint DEFAULT NULL,
  `matching_records_per_minute` bigint DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `unq_backfill_run_id_partition_name` (`backfill_run_id`,`partition_name`),
  KEY `idx_run_state_lease_expires_at` (`run_state`,`lease_expires_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
